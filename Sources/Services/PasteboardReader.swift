import AppKit
import Foundation

/// 从系统剪贴板抓到的一块内容。
struct ClipDraft: Sendable {
    var id = UUID()
    var kind: ClipKind = .text
    var text: String?
    var rtfData: Data?
    var rtfBlob: String?
    var imageData: Data?
    var imageBlob: String?
    var thumbBlob: String?
    var filePaths: [String]?
    var byteCount: Int = 0
    var contentHash: String = ""
    var sourceName: String?
    var sourceBundleID: String?
}

/// 解析剪贴板内容。
enum PasteboardReader {
    /// 我们自己写回剪贴板时打上的标记，用来区分“系统里的新内容”和“我们的粘贴动作”。
    static let markerType = NSPasteboard.PasteboardType("com.river.clip.marker")

    /// 密码管理器等应用会给内容打上这些标记，默认不记录。
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "com.agilebits.onepassword",
        "Pasteboard generator type",
    ]

    static func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        guard let types = pasteboard.types else { return false }
        return types.contains { concealedTypes.contains($0.rawValue) }
    }

    /// 读取剪贴板；无法识别或内容不合适时返回 nil。
    static func read(_ pasteboard: NSPasteboard, maxItemBytes: Int) -> ClipDraft? {
        let source = NSWorkspace.shared.frontmostApplication
        let sourceName = source?.localizedName
        let sourceBundleID = source?.bundleIdentifier

        if let draft = readFiles(pasteboard, sourceName: sourceName, sourceBundleID: sourceBundleID) {
            return draft
        }
        if let draft = readText(pasteboard, sourceName: sourceName, sourceBundleID: sourceBundleID) {
            return draft
        }
        if let draft = readImage(pasteboard, maxItemBytes: maxItemBytes, sourceName: sourceName, sourceBundleID: sourceBundleID) {
            return draft
        }
        return nil
    }

    // MARK: 文件

    private static func readFiles(_ pasteboard: NSPasteboard, sourceName: String?, sourceBundleID: String?) -> ClipDraft? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
              !urls.isEmpty else { return nil }
        let paths = urls.filter(\.isFileURL).map(\.path)
        guard !paths.isEmpty else { return nil }
        let text = paths.joined(separator: "\n")
        return ClipDraft(
            kind: .file,
            text: text,
            filePaths: paths,
            byteCount: text.utf8.count,
            contentHash: ContentHash.sha256("file:" + text),
            sourceName: sourceName,
            sourceBundleID: sourceBundleID
        )
    }

    // MARK: 文本 / 链接 / 颜色

    private static func readText(_ pasteboard: NSPasteboard, sourceName: String?, sourceBundleID: String?) -> ClipDraft? {
        guard let text = pasteboard.string(forType: .string) else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.count <= 120_000 else { return nil }

        let kind: ClipKind
        if ColorValue.parse(text) != nil {
            kind = .color
        } else if LinkDetector.isLink(trimmed) {
            kind = .link
        } else {
            kind = .text
        }

        var draft = ClipDraft(
            kind: kind,
            text: text,
            byteCount: text.utf8.count,
            contentHash: ContentHash.sha256("text:" + text),
            sourceName: sourceName,
            sourceBundleID: sourceBundleID
        )
        // 保留富文本，粘贴时可以还原格式
        if let rtf = pasteboard.data(forType: .rtf), rtf.count <= 1_000_000 {
            draft.rtfData = rtf
            draft.rtfBlob = "\(draft.id.uuidString).rtf"
        }
        return draft
    }

    // MARK: 图片

    private static func readImage(_ pasteboard: NSPasteboard, maxItemBytes: Int, sourceName: String?, sourceBundleID: String?) -> ClipDraft? {
        guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), !data.isEmpty else {
            return nil
        }
        let id = UUID()
        var draft = ClipDraft(
            kind: .image,
            imageData: data,
            byteCount: data.count,
            sourceName: sourceName,
            sourceBundleID: sourceBundleID
        )
        draft.id = id
        draft.imageBlob = "\(id.uuidString).png"
        draft.thumbBlob = "\(id.uuidString).jpg"
        return draft
    }
}

/// 颜色值识别。
enum ColorValue {
    static func parse(_ raw: String) -> NSColor? {
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard (4...32).contains(text.count) else { return nil }

        if text.hasPrefix("#") || text.hasPrefix("0x") || text.hasPrefix("0X") {
            return NSColor(clipHex: text)
        }
        let lower = text.lowercased()
        if lower.hasPrefix("rgb") {
            let numbers = text
                .components(separatedBy: CharacterSet(charactersIn: "0123456789.").inverted)
                .filter { !$0.isEmpty }
                .compactMap(Double.init)
            guard numbers.count >= 3 else { return nil }
            let scale = numbers.prefix(3).contains { $0 > 1 } ? 255.0 : 1.0
            var alpha = numbers.count >= 4 ? numbers[3] : 1
            // alpha 与 RGB 同尺度：rgba(255,0,0,128) 的 128 也是按 255 写的
            if scale == 255, alpha > 1 { alpha /= 255 }
            return NSColor(
                srgbRed: numbers[0] / scale,
                green: numbers[1] / scale,
                blue: numbers[2] / scale,
                alpha: alpha
            )
        }
        if let named = NSColor(named: text) { return named }
        return nil
    }
}

extension NSColor {
    /// 解析 #RGB / #RRGGBB / #RRGGBBAA。
    convenience init?(clipHex raw: String) {
        var text = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if text.hasPrefix("0x") { text.removeFirst(2) }
        if text.hasPrefix("#") { text.removeFirst() }
        guard text.allSatisfy(\.isHexDigit) else { return nil }

        if text.count == 3 {
            text = text.map { "\($0)\($0)" }.joined()
        }
        guard text.count == 6 || text.count == 8, let value = UInt64(text, radix: 16) else { return nil }

        let hasAlpha = text.count == 8
        let red = Double((value >> (hasAlpha ? 24 : 16)) & 0xFF) / 255
        let green = Double((value >> (hasAlpha ? 16 : 8)) & 0xFF) / 255
        let blue = Double((value >> (hasAlpha ? 8 : 0)) & 0xFF) / 255
        let alpha = hasAlpha ? Double(value & 0xFF) / 255 : 1
        self.init(srgbRed: red, green: green, blue: blue, alpha: alpha)
    }

    /// 输出 #RRGGBB（带透明度时输出 #RRGGBBAA）。
    var clipHexString: String {
        guard let rgb = usingColorSpace(.sRGB) else { return "#000000" }
        let red = Int((rgb.redComponent * 255).rounded())
        let green = Int((rgb.greenComponent * 255).rounded())
        let blue = Int((rgb.blueComponent * 255).rounded())
        let alpha = Int((rgb.alphaComponent * 255).rounded())
        return alpha >= 255
            ? String(format: "#%02X%02X%02X", red, green, blue)
            : String(format: "#%02X%02X%02X%02X", red, green, blue, alpha)
    }
}

/// 链接识别。
enum LinkDetector {
    private static let allowedSchemes: Set<String> = ["http", "https", "ftp", "mailto", "ssh", "git", "file"]

    static func isLink(_ text: String) -> Bool {
        guard !text.contains(" "), !text.contains("\n"), text.count <= 2048 else { return false }
        if let url = URL(string: text), let scheme = url.scheme?.lowercased() {
            if allowedSchemes.contains(scheme) {
                return scheme == "mailto" || url.host() != nil
            }
            return false
        }
        return text.hasPrefix("www.")
    }
}
